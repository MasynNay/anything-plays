"""Prove the actual installed 3.1.1 stable frozen desktop starts (private QA).

Input: the REAL FULL 18-console installer, one exact-byte assembler receipt,
the mounted/extracted frozen app, and the real Tk smoke JSON generated by
executing that frozen binary. No recording, game ROM, physical camera, or
public/legal approval is implied. A source-shell or QA-identity app fails.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

from anything_plays.v30_gpl_trial import validate_trial_core_directory
from tools.probe_v30_installed_desktop_window import validate_report
from tools.verify_v31_rc import validate_staged_identity
from tools.verify_v311_stable_source_stage import INSTALLERS, digest

QA_STATUS = {
    "linux-x64": "PRIVATE_3_1_1_FULL_STABLE_UPDATE_LINUX_NOT_APPROVED",
    "windows-x64": "PRIVATE_3_1_1_FULL_STABLE_UPDATE_WINDOWS_NOT_APPROVED",
    "macos-arm64": "PRIVATE_3_1_1_FULL_STABLE_UPDATE_MACOS_NOT_APPROVED",
    "macos-x64": "PRIVATE_3_1_1_FULL_STABLE_UPDATE_MACOS_NOT_APPROVED",
}
PASSED_STATUS = "PASSED_PRIVATE_3_1_1_REAL_FROZEN_18_CONSOLE_TK_SMOKE_NOT_RELEASE"
SOURCE_RE = re.compile(r"[0-9a-f]{40}\Z")


def _read_report(path):
    path = Path(path)
    if (not path.is_file() or path.is_symlink()
            or not 0 < path.stat().st_size < 1024 * 1024):
        raise ValueError("Missing or unsafe frozen-GUI evidence JSON")
    result = json.loads(path.read_text("utf-8"))
    if not isinstance(result, dict):
        raise ValueError("Frozen-GUI report is not a JSON object")
    return result


def verify(target, installer, app, receipt, smoke, source_revision):
    if target not in INSTALLERS or target not in QA_STATUS:
        raise ValueError("Unreviewed 3.1.1 installed target")
    if not isinstance(source_revision, str) or SOURCE_RE.fullmatch(source_revision) is None:
        raise ValueError("Exact 3.1.1 source SHA required")
    installer, app = Path(installer), Path(app)
    if (installer.name != INSTALLERS[target]
            or not installer.is_file() or installer.is_symlink()
            or installer.stat().st_size < 1024 * 1024
            or not app.is_dir() or app.is_symlink()):
        raise ValueError("Missing genuine stable 3.1.1 installer or installed application")
    identity = validate_staged_identity(app, channel="v311_stable_candidate")
    native_sha = digest(installer)
    expected = {
        "status": QA_STATUS[target],
        "target": target,
        "installer": INSTALLERS[target],
        "version": "3.1.1",
        "identity_channel": "v311_stable_candidate",
        "settings_namespace": "anything-plays-31",
        "stable_in_place_update": True,
        "native_core_count": 11,
        "console_profiles": 18,
        "public_release_approved": False,
        "full_four_platform_311_verified": False,
    }
    for key, value in expected.items():
        if type(receipt.get(key)) is not type(value) or receipt.get(key) != value:
            raise ValueError("Wrong full 3.1.1 stable-update assembler receipt: " + key)
    if target == "linux-x64":
        if (receipt.get("installer_sha256") != native_sha
                or receipt.get("app_source_sha") != source_revision):
            raise ValueError("Linux installed binary/hash/source revision differ from original")
        core_dir = app / "cores"
        suffix = ".so"
    else:
        if (receipt.get("sha256") != native_sha
                or receipt.get("new_source_revision") != source_revision):
            raise ValueError("Mac/Windows installed binary/hash/source revision mismatch")
        core_dir = (app / "Contents/Resources/cores" if target.startswith("macos")
                    else app / "cores")
        suffix = ".dylib" if target.startswith("macos") else ".dll"
    native = validate_trial_core_directory(core_dir, suffix)
    for key, value in {
        "native_core_count": 11,
        "total_source_built_core_families": 11,
        "all_console_profiles": 18,
    }.items():
        if native.get(key) != value:
            raise ValueError("Full 3.1.1 installed native core receipt invalid: " + key)
    if not native.get("source_built_dolphin") or not native.get("source_built_tia"):
        raise ValueError("Missing complete source-reviewed dolphin/Tia native core lineage")
    if not isinstance(smoke, dict):
        raise ValueError("Missing real frozen-window smoke report")
    validate_report(smoke, target)
    if (smoke.get("stream_output_window_opened") is not True
            or smoke.get("stream_closed_cleanly") is not True
            or smoke.get("stream_appearance_configured") is not True):
        raise ValueError("3.1.1 must launch its real 3.1 Stream Mode and close cleanly")
    return {
        "schema_version": 1,
        "status": PASSED_STATUS,
        "target": target,
        "installer": INSTALLERS[target],
        "installer_sha256": native_sha,
        "source_revision": source_revision,
        "embedded_stable_identity": identity,
        "stable_settings_namespace_retained": True,
        "frozen_desktop_started": True,
        "stream_mode_started_and_closed": True,
        "native_core_count": 11,
        "console_profiles": 18,
        "hardware_gameplay_verified": False,
        "physical_camera_verified": False,
        "physical_controller_verified": False,
        "third_party_relinking_verified": False,
        "public_release_approved": False,
    }


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--target",choices=tuple(INSTALLERS),required=True)
    p.add_argument("--source-sha",required=True)
    for name in ("installer","app","receipt","smoke","output"):
        p.add_argument("--"+name,type=Path,required=True)
    a=p.parse_args()
    result=verify(a.target,a.installer,a.app,_read_report(a.receipt),
                  _read_report(a.smoke),a.source_sha)
    a.output.parent.mkdir(parents=True,exist_ok=True)
    a.output.write_text(json.dumps(result,indent=2)+"\n","utf-8")
    print("Original frozen 3.1.1 desktop verified:",result["target"],
          "18 consoles, no hardware/release approval")


if __name__=="__main__":
    main()
